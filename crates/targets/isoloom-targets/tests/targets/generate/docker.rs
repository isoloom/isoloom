//! The `docker` target's Compose file: addresses, health, init jobs, routes through the router or a
//! gateway, Docker's blocks and the start plan, read from the parsed file.

use isoloom_spec::Target;
use isoloom_targets::{Lab, generate};
use isoloom_test_support::{yaml, yaml_at, yaml_keys_at, yaml_str, yaml_strs};
use serde::Deserialize as _;
use serde_yaml_ng::Value;

use crate::testing::{Outcome, example, file, generated, lab};

/// The Compose file `lab` generates, parsed, with its text (for the header comments).
fn compose(lab: &Lab) -> Outcome<(Value, String)> {
    let text = generated(lab, Target::Docker, "docker/compose.yml")?;
    Ok((yaml(&text), text))
}

/// The command service `name` runs: its entrypoint and command, one item a line.
fn script(c: &Value, name: &str) -> String {
    let service = format!("services.`{name}`");
    [yaml_strs(c, &format!("{service}.entrypoint")), yaml_strs(c, &format!("{service}.command"))]
        .concat()
        .join("\n")
}

/// The services service `name` waits for, each with the condition it waits for.
fn waits_for(c: &Value, name: &str) -> Vec<(String, String)> {
    let at = format!("services.`{name}`.depends_on");
    yaml_keys_at(c, &at)
        .into_iter()
        .map(|dep| {
            let condition = yaml_str(c, &format!("{at}.`{dep}`.condition"));
            (dep, condition)
        })
        .collect()
}

/// Every environment variable and secret service `name` is given, by name.
fn inputs_of(c: &Value, name: &str) -> Vec<String> {
    let service = format!("services.`{name}`");
    let mut out = yaml_keys_at(c, &format!("{service}.environment"));
    out.extend(
        yaml_at(c, &format!("{service}.secrets"))
            .and_then(Value::as_sequence)
            .into_iter()
            .flatten()
            .filter_map(|s| s.get("source").and_then(Value::as_str).map(str::to_owned)),
    );
    out
}

#[test]
fn compose_has_addresses_healthchecks_init_and_checks() -> Outcome {
    let spec = example("hello-stack")?;
    let (c, text) = compose(&spec)?;
    assert!(text.starts_with("# Generated by isoloom"));
    assert_eq!(yaml_str(&c, "services.cache.networks.app.ipv4_address"), "10.60.0.20");
    assert_eq!(yaml_str(&c, "networks.app.ipam.config.0.gateway"), "10.60.0.1");
    // The healthcheck runs Isoloom's own busybox (exec form): no shell needed in the image.
    let health = yaml_strs(&c, "services.cache.healthcheck.test");
    assert_eq!(health.first().map(String::as_str), Some("CMD"));
    assert_eq!(health.last().map(String::as_str), Some("/.isoloom-probe/busybox nc -z -w 2 127.0.0.1 6379"));
    assert!(yaml_strs(&c, "services.cache.volumes").contains(&"isoloom-probe:/.isoloom-probe:ro".to_owned()));
    assert!(yaml_str(&c, "services.isoloom-probe.image").starts_with("busybox:1.37.0-musl@sha256:"));
    // The init job waits for its machine; the machine that depends on it waits for the job.
    assert!(waits_for(&c, "isoloom-init-cache-1").contains(&("cache".to_owned(), "service_healthy".to_owned())));
    assert!(waits_for(&c, "web").contains(&("isoloom-init-cache-1".to_owned(), "service_completed_successfully".to_owned())));
    // The runners: one on every network (no access machine), one per machine in its namespace.
    assert_eq!(yaml_strs(&c, "services.isoloom-check.profiles"), ["check"]);
    assert_eq!(yaml_str(&c, "services.isoloom-check-web.network_mode"), "service:web");
    let files = generate(&spec, Target::Docker)?;
    let runner = file(&files, ".isoloom/docker/checks/isoloom-networks.sh")?;
    assert!(runner.contains("cd /isoloom/project && sh '\\''checks/cache-seeded.sh'\\''"), "{runner}");
    assert!(runner.contains("_http_is 'http://web/' 200"), "{runner}");
    Ok(())
}

#[test]
fn inputs_reach_only_the_machines_that_list_them() -> Outcome {
    let (c, _) = compose(&example("supplier-portal-api")?)?;
    assert_eq!(inputs_of(&c, "web"), Vec::<String>::new(), "web must not receive the database's inputs");
    assert_eq!(yaml_str(&c, "services.database.environment.API_URL"), "${API_URL:-}");
    // A sensitive input is a file, read from the runner's environment: never an environment
    // variable of the machine.
    assert_eq!(yaml_str(&c, "secrets.input-launch-token.environment"), "LAUNCH_TOKEN");
    assert!(!yaml_keys_at(&c, "services.database.environment").contains(&"LAUNCH_TOKEN".to_owned()));
    Ok(())
}

/// The shape of a published CTF lab (`examples/invoice-portal-api`): the API on 80 published on the
/// host's fixed 8080, the launch URL an environment value and the launch token a file of the
/// database only, the setup step and its volume, and both the `http` check and the script.
#[test]
fn a_ctf_labs_shape_keeps_its_port_inputs_setup_and_checks() -> Outcome {
    let spec = example("invoice-portal-api")?;
    let (c, _) = compose(&spec)?;
    assert_eq!(yaml_strs(&c, "services.web.ports"), ["${ISOLOOM_PUBLISH_ADDRESS:-127.0.0.1}:8080:80"]);
    assert_eq!(inputs_of(&c, "web"), Vec::<String>::new(), "web must not receive the database's inputs");
    assert_eq!(inputs_of(&c, "database"), ["CTF_API_URL", "input-ctf-launch-token"]);
    assert_eq!(yaml_str(&c, "services.database.environment.CTF_API_URL"), "${CTF_API_URL:-}");
    assert_eq!(yaml_str(&c, "secrets.input-ctf-launch-token.environment"), "CTF_LAUNCH_TOKEN");
    assert_eq!(yaml_str(&c, "services.database.secrets.0.target"), "/run/lab/launch-token");
    assert_eq!(
        yaml_strs(&c, "services.isoloom-init-database-1.entrypoint"),
        ["/bin/sh", "/isoloom/init/evidence.sh"]
    );
    assert!(yaml_strs(&c, "services.isoloom-init-database-1.volumes").contains(&"database-evidence:/var/lib/ctf".to_owned()));
    let files = generate(&spec, Target::Docker)?;
    let runners: String = files.iter().filter(|f| f.path.contains("/checks/")).map(|f| f.contents.as_str()).collect();
    assert!(runners.contains("_http_is 'http://web/api/invoices/INV-1042' 401"), "{runners}");
    assert!(runners.contains("build/check/check.sh"), "{runners}");
    Ok(())
}

#[test]
fn reach_rules_add_a_router_with_matching_rules() -> Outcome {
    let (c, _) = compose(&example("segmented")?)?;
    assert_eq!(
        yaml_str(&c, "services.isoloom-router.networks.back.ipv4_address"),
        "10.61.20.254",
        "router at the last address"
    );
    let rules = yaml_str(&c, "services.isoloom-router.environment.RULES");
    assert!(rules.contains("ip saddr 10.61.99.0/24 ip daddr 10.61.10.0/24 accept"), "{rules}");
    assert!(rules.contains("th dport { 6379 }") && rules.contains("policy drop"), "{rules}");
    // Routes via the router, in the machine's own network namespace.
    assert_eq!(yaml_str(&c, "services.isoloom-routes-web.network_mode"), "service:web");
    let routes = script(&c, "isoloom-routes-web");
    assert!(routes.contains("ip route replace 10.61.20.0/24 via 10.61.10.254"), "{routes}");
    // Offline machines lose their default route; no Docker-internal network with a router.
    let offline = yaml_keys_at(&c, "services").into_iter().map(|s| script(&c, &s)).collect::<Vec<_>>().join("\n");
    assert!(offline.contains("ip route del default"));
    assert!(
        yaml_keys_at(&c, "networks")
            .iter()
            .all(|n| yaml_at(&c, &format!("networks.{n}.internal")).is_none())
    );
    // Names across networks, and checks from the access machine's position. The access box is on
    // demand (the `access` profile), so a check in the `check` profile can't share its namespace:
    // it runs from the stand-in at the box's addresses (`isoloom-access`), not the box itself.
    assert!(yaml_strs(&c, "services.web.extra_hosts").contains(&"cache:10.61.20.20".to_owned()));
    assert_eq!(yaml_str(&c, "services.isoloom-check.network_mode"), "service:isoloom-access");
    Ok(())
}

#[test]
fn a_gateway_routes_its_networks_instead_of_the_router() -> Outcome {
    let (c, _) = compose(&example("edge-firewall")?)?;
    let services = yaml_keys_at(&c, "services");
    assert!(!services.contains(&"isoloom-router".to_owned()), "no router: the firewall routes");
    // The firewall takes .1; Docker's bridge moves to the last address on its networks.
    assert_eq!(yaml_str(&c, "services.fw.networks.dmz.ipv4_address"), "10.70.10.1");
    assert_eq!(yaml_str(&c, "networks.dmz.ipam.config.0.gateway"), "10.70.10.254");
    assert_eq!(yaml_str(&c, "networks.outside.ipam.config.0.gateway"), "10.70.0.1");
    assert_eq!(yaml_str(&c, "services.fw.sysctls.`net.ipv4.ip_forward`"), "1");
    // Machines behind it send everything through it, once it answers.
    let web = script(&c, "isoloom-routes-web");
    assert!(web.contains("ip route replace default via 10.70.10.1"), "{web}");
    let all = services.iter().map(|s| script(&c, s)).collect::<Vec<_>>().join("\n");
    assert!(all.contains("ip route replace 10.70.10.0/24 via 10.70.0.5"), "{all}");
    assert!(waits_for(&c, "isoloom-routes-web").contains(&("fw".to_owned(), "service_healthy".to_owned())));
    // Its own rules decide: no Docker-internal network, no route deletion.
    assert!(
        yaml_keys_at(&c, "networks")
            .iter()
            .all(|n| yaml_at(&c, &format!("networks.{n}.internal")).is_none())
    );
    assert!(!all.contains("ip route del default"));
    Ok(())
}

#[test]
fn networks_outside_10_move_into_10_on_docker_keeping_last_octets() -> Outcome {
    let spec = lab(
        "version: 1\nname: t\nnetworks:\n  corp: { cidr: 192.168.20.0/24 }\n  dmz: { cidr: 172.18.5.0/24 }\n  taken: { cidr: 10.192.20.0/24 }\nmachines:\n  a: { os: debian@12, networks: { corp: 10, dmz: 7, taken: 9 }, app: { image: x, steps: [{ run: p.sh }] } }\n",
    )?;
    assert_eq!(spec.problems(), vec![]);
    let (c, text) = compose(&spec)?;
    // 172.N.X -> 10.N.X; 192.168.X -> 10.192.X, taken here, so the next free block.
    assert_eq!(yaml_str(&c, "networks.dmz.ipam.config.0.subnet"), "10.18.5.0/24");
    assert_eq!(yaml_str(&c, "services.a.networks.dmz.ipv4_address"), "10.18.5.7");
    assert_eq!(yaml_str(&c, "networks.corp.ipam.config.0.subnet"), "10.240.0.0/24");
    assert_eq!(yaml_str(&c, "services.a.networks.corp.ipv4_address"), "10.240.0.10");
    assert!(text.contains("# On Docker, network `corp` uses 10.240.0.0/24 instead of 192.168.20.0/24"));
    // VMs keep the spec's addresses.
    let vf = generated(&spec, Target::Vagrant, "vagrant/Vagrantfile")?;
    assert!(vf.contains("ip: \"192.168.20.10\""));
    Ok(())
}

#[test]
fn a_network_can_name_its_docker_block() -> Outcome {
    let base = "version: 1\nname: t\nnetworks:\n  corp: { cidr: 192.168.20.0/24 }\nmachines:\n  a: { networks: { corp: 10 }, app: { image: x } }\noverrides: { docker: { networks: { corp: { cidr: DOCKER } } } }\n";
    let spec = lab(&base.replace("DOCKER", "10.77.0.0/24"))?;
    assert_eq!(spec.problems(), vec![]);
    let (c, _) = compose(&spec)?;
    assert_eq!(yaml_str(&c, "services.a.networks.corp.ipv4_address"), "10.77.0.10");
    for bad in ["10.77.0.0/25", "172.20.0.0/24"] {
        let found = lab(&base.replace("DOCKER", bad))?.problems();
        assert!(
            found.iter().any(|x| x.path.as_str() == "overrides.docker.networks.corp.cidr"),
            "{bad}: {found:?}"
        );
    }
    Ok(())
}

#[test]
fn an_idle_container_is_kept_running() -> Outcome {
    // The OS alone: its official image, pinned, kept running idle under the engine's init.
    let spec = lab(
        "version: 1\nname: idle\nnetworks:\n  lan: { cidr: 10.10.1.0/24 }\nmachines:\n  box:\n    os: alpine\n    networks: { lan: 10 }\n  web:\n    networks: { lan: 11 }\n    ports: { web: 80 }\n    app: { image: \"nginx:1.27-alpine\" }\n",
    )?;
    let image = spec.source().machines["box"].os.unwrap().os().container_image().unwrap();
    let (c, _) = compose(&spec)?;
    assert_eq!(yaml_str(&c, "services.box.image"), image);
    assert_eq!(yaml_str(&c, "services.box.init"), "true");
    assert_eq!(yaml_strs(&c, "services.box.entrypoint"), ["sleep", "infinity"]);
    // A machine that runs its own service keeps its image's command.
    assert!(yaml_at(&c, "services.web.entrypoint").is_none());
    let k8s: Vec<Value> = generate(&spec, Target::Kubernetes)?
        .iter()
        .filter(|f| std::path::Path::new(&f.path).extension().is_some_and(|e| e == "yaml"))
        .flat_map(|f| serde_yaml_ng::Deserializer::from_str(&f.contents).map(Value::deserialize).collect::<Vec<_>>())
        .collect::<Result<_, _>>()?;
    let deployment = k8s
        .iter()
        .find(|d| yaml_str(d, "kind") == "Deployment" && yaml_str(d, "metadata.name") == "box")
        .ok_or("no Deployment for box")?;
    assert_eq!(yaml_strs(deployment, "spec.template.spec.containers.0.command"), ["sleep", "infinity"]);
    Ok(())
}

/// An init job on a machine nothing depends on is a leaf job: `up --wait` would fail on its exit,
/// so one service of Isoloom's own waits for it to complete, and the one `up --wait` covers it.
#[test]
fn leaf_init_jobs_are_waited_for_by_the_one_up() -> Outcome {
    let spec = lab(r#"
version: 1
name: leaf
networks: { lan: { cidr: 10.70.0.0/24 } }
machines:
  db:
    networks: { lan: 20 }
    ports: { db: 5432 }
    app: { image: "postgres:17" }
    setup: [seed.sh]
  web:
    networks: { lan: 10 }
    ports: { web: 80 }
    depends_on: [db]
    app: { image: "nginx:1.27-alpine" }
    setup: [setup.sh, warm.sh]
"#)?;
    // db's job is waited for by web; web's two jobs by nothing but `isoloom-jobs-done`, which
    // `--wait` waits for: a job that fails fails the `up`.
    let (c, text) = compose(&spec)?;
    let dc = "docker compose -f .isoloom/docker/compose.yml";
    assert!(text.contains(&format!("# Start:  {dc} up -d --build --wait\n")), "{text}");
    assert!(!text.contains("--exit-code-from"), "{text}");
    let done = waits_for(&c, "isoloom-jobs-done");
    let jobs: Vec<&str> = done
        .iter()
        .map(|(job, _)| job.as_str())
        .filter(|job| job.starts_with("isoloom-init-"))
        .collect();
    assert_eq!(jobs, ["isoloom-init-web-1", "isoloom-init-web-2"], "web waits for db's: {done:?}");
    assert!(
        done.iter()
            .filter(|(job, _)| job.starts_with("isoloom-init-"))
            .all(|(_, condition)| condition == "service_completed_successfully")
    );
    // Nothing left over: the one command it always was.
    let (_, plain) = compose(&example("hello-stack")?)?;
    assert!(plain.contains(&format!("# Start:  {dc} up -d --build --wait\n")), "{plain}");
    Ok(())
}
