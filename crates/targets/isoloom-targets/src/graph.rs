//! The environment drawn from its resolved snapshot (`isoloom graph`): networks as hexagons,
//! machines as boxes (the access machine as a person, gateways as diamonds), membership edges
//! labeled with the last octet, the router, and `reach` as dashed arrows between networks
//! labeled with their ports. As D2 ([`d2`]) or Graphviz DOT ([`dot`]); each tool renders it to
//! SVG or PNG.

use serde_json::Value;

use crate::resolved::{entries, ports};

/// What a machine is drawn as: each format has its own shape for each.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum MachineKind {
    Access,
    Gateway,
    Other,
}

impl MachineKind {
    /// What the snapshot's machine `v` is.
    fn of(v: &Value) -> MachineKind {
        if v.get("access").and_then(Value::as_bool) == Some(true) {
            MachineKind::Access
        } else if v.get("gateway_of").and_then(Value::as_array).is_some_and(|g| !g.is_empty()) {
            MachineKind::Gateway
        } else {
            MachineKind::Other
        }
    }
}

/// The text at `key` of `v`, or `default`.
fn text<'a>(v: &'a Value, key: &str, default: &'a str) -> &'a str {
    v.get(key).and_then(Value::as_str).unwrap_or(default)
}

/// The networks the router joins, when there is one.
fn router_networks(r: &Value) -> Option<impl Iterator<Item = &str>> {
    let router = r.get("router").and_then(Value::as_object)?;
    Some(router.get("networks").and_then(Value::as_array).into_iter().flatten().filter_map(Value::as_str))
}

/// The graph as D2 (<https://d2lang.com>). Render: `d2 name.d2 name.svg`.
#[must_use]
pub fn d2(r: &Value) -> String {
    let name = text(r, "name", "environment");
    let mut lines = vec![
        format!("# {name}: generated by isoloom graph. Render: d2 {name}.d2 {name}.svg"),
        "direction: right\n".to_owned(),
    ];
    lines.extend(entries(r, "networks").map(|(net, n)| format!("net_{}: \"{}\" {{ shape: hexagon }}", id(net), network_label(net, n))));
    lines.push(String::new());
    for (m, v) in entries(r, "machines") {
        let ports: Vec<String> = entries(v, "ports").map(|(n, s)| format!("{} {n}", ports::shown(s))).collect();
        let label = if ports.is_empty() { m.clone() } else { format!("{m}\\n{}", ports.join(", ")) };
        let shape = match MachineKind::of(v) {
            MachineKind::Access => "person",
            MachineKind::Gateway => "diamond",
            MachineKind::Other => "rectangle",
        };
        lines.push(format!("m_{}: \"{label}\" {{ shape: {shape} }}", id(m)));
        lines.extend(octets(v).map(|(net, octet)| format!("m_{} -- net_{}: \".{octet}\"", id(m), id(net))));
    }
    if let Some(nets) = router_networks(r) {
        lines.push("\nrouter: \"router\\n(reach rules)\" { shape: cylinder }".to_owned());
        lines.extend(nets.map(|net| format!("router -- net_{}", id(net))));
    }
    let reach: Vec<String> = reach(r)
        .map(|(from, to, label)| format!("net_{} -> net_{}: \"{label}\" {{ style.stroke-dash: 3 }}", id(from), id(to)))
        .collect();
    if !reach.is_empty() {
        lines.push(String::new());
        lines.extend(reach);
    }
    format!("{}\n", lines.join("\n"))
}

/// The graph as Graphviz DOT. Render: `dot -Tsvg -o name.svg name.dot`.
#[must_use]
pub fn dot(r: &Value) -> String {
    let name = text(r, "name", "environment");
    let mut lines = vec![
        format!("// {name}: generated by isoloom graph. Render: dot -Tsvg -o {name}.svg {name}.dot"),
        format!("digraph \"{name}\" {{\n  rankdir=LR;\n  node [fontname=\"Helvetica\", fontsize=10];\n  edge [fontname=\"Helvetica\", fontsize=9];"),
    ];
    lines.extend(entries(r, "networks").map(|(net, n)| {
        format!(
            "  net_{} [label=\"{}\", shape=hexagon, style=filled, fillcolor=\"#eeeeee\"];",
            id(net),
            network_label(net, n)
        )
    }));
    for (m, v) in entries(r, "machines") {
        let ports: Vec<String> = entries(v, "ports").map(|(_, s)| ports::shown(s)).collect();
        let label = if ports.is_empty() {
            m.clone()
        } else {
            format!("{m}\\n:{}", ports.join(" :"))
        };
        let shape = match MachineKind::of(v) {
            MachineKind::Access => "egg",
            MachineKind::Gateway => "diamond",
            MachineKind::Other => "box",
        };
        lines.push(format!("  m_{} [label=\"{label}\", shape={shape}];", id(m)));
        lines.extend(octets(v).map(|(net, octet)| format!("  m_{} -> net_{} [label=\".{octet}\", dir=none];", id(m), id(net))));
    }
    if let Some(nets) = router_networks(r) {
        lines.push("  router [label=\"router\\n(reach rules)\", shape=cylinder];".to_owned());
        lines.extend(nets.map(|net| format!("  router -> net_{} [dir=none];", id(net))));
    }
    lines.extend(reach(r).map(|(from, to, label)| format!("  net_{} -> net_{} [label=\"{label}\", style=dashed, color=\"#555555\"];", id(from), id(to))));
    lines.push("}".to_owned());
    format!("{}\n", lines.join("\n"))
}

/// A network's label: its name, its block, and `no internet` when offline.
fn network_label(net: &str, n: &Value) -> String {
    let mut label = format!("{net}\\n{}", text(n, "cidr", ""));
    if n.get("internet").and_then(Value::as_bool) == Some(false) {
        label.push_str("\\nno internet");
    }
    label
}

/// A machine's networks, each with the last octet of its address there.
fn octets(v: &Value) -> impl Iterator<Item = (&String, &str)> {
    entries(v, "addresses").map(|(net, addr)| (net, addr.as_str().and_then(|a| a.rsplit('.').next()).unwrap_or("")))
}

/// The `reach` rules as (from, to, their ports or `all ports`).
fn reach(r: &Value) -> impl Iterator<Item = (&str, &str, String)> {
    r.get("reach").and_then(Value::as_array).into_iter().flatten().map(|rule| {
        let ports: Vec<String> = rule
            .get("ports")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .map(Value::to_string)
            .collect();
        let label = if ports.is_empty() { "all ports".to_owned() } else { ports.join(", ") };
        (text(rule, "from", ""), text(rule, "to", ""), label)
    })
}

/// A name as a D2/DOT identifier.
fn id(name: &str) -> String {
    name.chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '_' }).collect()
}

#[cfg(test)]
mod tests {
    use serde_json::json;

    use super::*;

    fn snapshot() -> Value {
        json!({
            "name": "lab",
            "networks": { "lan": { "cidr": "10.0.0.0/24", "internet": false } },
            "machines": {
                "web": { "addresses": { "lan": "10.0.0.10" }, "ports": { "site": { "port": 80, "protocol": "http" } } },
                "user": { "access": true, "addresses": { "lan": "10.0.0.20" }, "ports": {} }
            },
            "reach": [{ "from": "lan", "to": "lan", "ports": [] }]
        })
    }

    #[test]
    fn d2_draws_networks_machines_and_reach() {
        let text = d2(&snapshot());
        assert!(
            text.starts_with("# lab: generated by isoloom graph. Render: d2 lab.d2 lab.svg\ndirection: right\n\n"),
            "{text}"
        );
        assert!(text.contains("net_lan: \"lan\\n10.0.0.0/24\\nno internet\" { shape: hexagon }\n"), "{text}");
        assert!(
            text.contains("m_web: \"web\\n80 site\" { shape: rectangle }\nm_web -- net_lan: \".10\"\n"),
            "{text}"
        );
        assert!(text.contains("m_user: \"user\" { shape: person }\n"), "{text}");
        assert!(text.ends_with("\nnet_lan -> net_lan: \"all ports\" { style.stroke-dash: 3 }\n"), "{text}");
    }

    #[test]
    fn dot_draws_the_same_as_a_digraph() {
        let text = dot(&snapshot());
        assert!(text.contains("  m_web [label=\"web\\n:80\", shape=box];\n"), "{text}");
        assert!(text.contains("  m_user [label=\"user\", shape=egg];\n"), "{text}");
        assert!(text.ends_with("style=dashed, color=\"#555555\"];\n}\n"), "{text}");
    }

    #[test]
    fn a_name_becomes_an_identifier() {
        assert_eq!(id("db-1.lab"), "db_1_lab");
    }

    proptest::proptest! {
        #[test]
        fn every_name_is_an_identifier_of_the_same_length(name in ".{0,30}") {
            let ident = id(&name);
            proptest::prop_assert!(ident.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'), "{}", ident);
            proptest::prop_assert_eq!(ident.chars().count(), name.chars().count());
        }
    }
}
