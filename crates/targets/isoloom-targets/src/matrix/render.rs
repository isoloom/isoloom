//! The matrix written out: text for a terminal, Markdown for `docs/matrix.md`, JSON for tools.

use isoloom_plan::Feature;
use serde_json::{Map, Value, json};

use super::{Cell, Matrix, Row};
use crate::decision::{Column, Refused};
use crate::tiers::Tier;

/// What the three marks mean.
const LEGEND: &str = "✓ generated, ✗ refused, – not applicable";

/// What the tiers mean.
fn tier_legend() -> String {
    let all = [Tier::One, Tier::Two, Tier::Three].map(|t| format!("{t} {}", t.meaning()));
    format!("Tiers: {}.", all.join(", "))
}

/// A cell's mark.
fn mark(cell: &Cell) -> &'static str {
    match cell {
        Cell::Supported => "✓",
        Cell::Refused(_) => "✗",
        Cell::NotApplicable => "–",
    }
}

/// Why a cell is refused, in a line: the step (and the capability lacking), then the reason.
fn why(r: &Refused) -> String {
    match r.code.feature() {
        Some(f) => format!("{} `{}`: {}", r.code.id(), f.id(), r.reason),
        None => format!("{}: {}", r.code.id(), r.reason),
    }
}

/// The columns of `row` grouped by what they decided (generated, each refusal, not
/// applicable), in column order; a target whose every column is in one group is named once
/// (`vagrant/*`).
fn groups<'a>(m: &Matrix, row: &'a Row) -> Vec<(&'a Cell, Vec<String>)> {
    let mut out: Vec<(&Cell, Vec<&Column>)> = Vec::new();
    for (column, cell) in m.columns.iter().zip(&row.cells) {
        match out.iter_mut().find(|(c, _)| *c == cell) {
            Some((_, cols)) => cols.push(column),
            None => out.push((cell, vec![column])),
        }
    }
    out.into_iter().map(|(cell, cols)| (cell, names(m, &cols))).collect()
}

/// The names of `cols`, a target's columns named `<target>/*` when all of them are there.
fn names(m: &Matrix, cols: &[&Column]) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for col in cols {
        let mine = m.columns.iter().filter(|c| c.target == col.target).count();
        let here = cols.iter().filter(|c| c.target == col.target).count();
        let name = if col.variant.is_some() && mine == here {
            format!("{}/*", col.target.id())
        } else {
            col.id()
        };
        if !out.contains(&name) {
            out.push(name);
        }
    }
    out
}

/// The tier list, one line per entry: its name, tier and evidence.
fn tier_lines(m: &Matrix) -> Vec<String> {
    let width = m.tiers.iter().map(|e| e.id().len()).max().unwrap_or_default();
    m.tiers
        .iter()
        .map(|e| format!("  {:<width$}  {}  {}", e.id(), e.tier(), e.evidence()))
        .collect()
}

/// The matrix as text.
pub(super) fn text(m: &Matrix) -> String {
    let mut lines = vec![
        format!("Capability matrix: what each target does with each spec field ({LEGEND})."),
        String::new(),
        tier_legend(),
    ];
    lines.extend(tier_lines(m));
    for row in &m.rows {
        lines.push(String::new());
        lines.push(format!("{}: {}", row.name(), row.about));
        for (cell, cols) in groups(m, row) {
            let cols = cols.join(", ");
            lines.push(match cell {
                Cell::Refused(r) => format!("  ✗ {cols}: {}", why(r)),
                other => format!("  {} {cols}", mark(other)),
            });
        }
    }
    lines.push(String::new());
    lines.join("\n")
}

/// A Markdown table cell's text, its pipes escaped.
fn md(text: &str) -> String {
    text.replace('|', "\\|")
}

/// The matrix as Markdown: the tiers, the grid, then why each refused cell is refused.
pub(super) fn markdown(m: &Matrix) -> String {
    let mut lines = vec![
        "# Capability matrix".to_owned(),
        String::new(),
        "<!-- Generated by `isoloom docs --matrix` from what each target decides. Change a target or the tier list (`cargo xtask tiers record`), then regenerate. -->".to_owned(),
        String::new(),
        format!(
            "What each target does with each spec field. Every cell is the target's own decision about a small lab that uses the field: {LEGEND}. The reasons follow the grid."
        ),
        String::new(),
        "## Tiers".to_owned(),
        String::new(),
        tier_legend(),
        String::new(),
        "| Target | Tier | Exists on | Evidence |".to_owned(),
        "|---|---|---|---|".to_owned(),
    ];
    for e in &m.tiers {
        let oses: Vec<&str> = e.exists_on.iter().map(|o| crate::tiers::os_id(*o)).collect();
        lines.push(format!("| `{}` | {} | {} | {} |", e.id(), e.tier(), oses.join(", "), md(&e.evidence())));
    }
    lines.extend([String::new(), "## Fields".to_owned(), String::new()]);
    lines.extend(grid(m));
    lines.extend([String::new(), "## Why a target refuses".to_owned()]);
    for row in m.rows.iter().filter(|r| r.cells.iter().any(|c| matches!(c, Cell::Refused(_)))) {
        lines.extend([String::new(), format!("### `{}`", row.name()), String::new()]);
        for (cell, cols) in groups(m, row) {
            if let Cell::Refused(r) = cell {
                let named: Vec<String> = cols.iter().map(|c| format!("`{c}`")).collect();
                lines.push(format!("- {}: {}", named.join(", "), md(&why(r))));
            }
        }
    }
    lines.push(String::new());
    lines.join("\n")
}

/// The grid: a header naming each column with its tiers, then a row of marks per field.
fn grid(m: &Matrix) -> Vec<String> {
    let heads: Vec<String> = m
        .columns
        .iter()
        .map(|c| {
            let tiers: Vec<String> = m.column_tiers(c).iter().map(Tier::to_string).collect();
            format!("`{}` ({})", c.id(), tiers.join("–"))
        })
        .collect();
    let mut lines = vec![
        format!("| Field | What | {} |", heads.join(" | ")),
        format!("|---|---|{}", "---|".repeat(heads.len())),
    ];
    for row in &m.rows {
        let marks: Vec<&str> = row.cells.iter().map(mark).collect();
        lines.push(format!("| `{}` | {} | {} |", md(&row.name()), md(&row.about), marks.join(" | ")));
    }
    lines
}

/// A cell as JSON: its state, and for a refusal its step, capability, field and reason.
fn cell_json(cell: &Cell) -> Value {
    match cell {
        Cell::Supported => json!({ "state": "supported" }),
        Cell::NotApplicable => json!({ "state": "not_applicable" }),
        Cell::Refused(r) => json!({
            "state": "refused",
            "code": r.code.id(),
            "feature": r.code.feature().map(Feature::id),
            "field": r.field,
            "reason": r.reason,
        }),
    }
}

/// The matrix as JSON: the columns with their tiers, every tier entry, then the rows, each cell
/// by its column's name.
pub(super) fn json(m: &Matrix) -> Value {
    let columns: Vec<Value> = m
        .columns
        .iter()
        .map(|c| {
            let tiers: Vec<u8> = m.column_tiers(c).into_iter().map(Tier::number).collect();
            json!({ "id": c.id(), "target": c.target.id(), "variant": c.variant, "tiers": tiers })
        })
        .collect();
    let rows: Vec<Value> = m
        .rows
        .iter()
        .map(|row| {
            let cells: Map<String, Value> = m.columns.iter().zip(&row.cells).map(|(c, cell)| (c.id(), cell_json(cell))).collect();
            json!({
                "field": row.field,
                "value": row.value,
                "about": row.about,
                "features": row.features.iter().map(|f| f.id()).collect::<Vec<_>>(),
                "cells": cells,
            })
        })
        .collect();
    json!({
        "columns": columns,
        "tiers": m.tiers.iter().map(crate::tiers::TierEntry::json).collect::<Vec<_>>(),
        "rows": rows,
    })
}
