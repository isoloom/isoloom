//! The environment as a Helm chart in `.isoloom/kubernetes/chart/`, written from the same
//! objects as the plain manifests: the namespace is the release's, each machine's image a value
//! (`images.<machine>`), the inputs a Secret from `inputs.<NAME>`, the checks `helm test` Pods
//! (the `exec` ones, run inside a machine, stay with `isoloom test`), and the project's scripts
//! read from `files/project/` (see [`crate::project_copies`]).
//!
//! The chart's templates are valid YAML before Helm renders them: what Helm fills in is a
//! quoted scalar (a [`Text::Helm`] or an [`Image::Value`] of the objects), and a `{{` already
//! in a manifest (a script, the message) is printed as it is.

use indexmap::IndexMap;
use isoloom_plan::Environment;
use isoloom_render::backend::RenderError;
use isoloom_render::{GeneratedFile, OUTPUT_DIR};
use serde::Serialize;
use serde_yaml_ng::Value;

use crate::kustomize::{CHECK_SCRIPTS, SCRIPTS, key};
use crate::machine::Machine;
use crate::objects::{HELM_TAG, Image, Labels, Manifest, Metadata, Spec, Text, go_string};
use crate::pod::INPUTS;
use crate::render::{Rendered, document, generated, unwritable};
use crate::{CHART, CHART_PROJECT_FILES, DIR};

/// `Chart.yaml`.
#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
struct ChartFile {
    api_version: &'static str,
    name: String,
    description: String,
    #[serde(rename = "type")]
    kind: &'static str,
    version: &'static str,
    app_version: &'static str,
}

/// `values.yaml`: each machine's image, and the inputs when a machine reads some.
#[derive(Debug, Serialize)]
struct Values {
    images: IndexMap<String, String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    inputs: Option<IndexMap<String, String>>,
}

/// The chart's files, under the target's folder.
pub(crate) fn files(env: &Environment, r: &Rendered) -> Result<Vec<GeneratedFile>, RenderError> {
    let file = |path: &str, contents: String| GeneratedFile {
        path: format!("{OUTPUT_DIR}/{DIR}/{CHART}/{path}"),
        contents,
    };
    let inputs = env.machines.values().any(|m| !m.inputs.is_empty());
    let mut out = vec![
        file("Chart.yaml", chart_file(env)?),
        file("values.yaml", values(env, inputs)?),
        file("templates/environment.yaml", environment(r)?),
    ];
    if !r.scripts.is_empty() {
        out.push(file("templates/scripts.yaml", scripts(&r.scripts)?));
    }
    if inputs {
        out.push(file("templates/inputs.yaml", secret(env)?));
    }
    if !r.checks.jobs.is_empty() {
        out.push(file("templates/tests/checks.yaml", tests(r)?));
        out.extend(r.checks.runners.iter().map(|(name, text)| file(&format!("files/checks/{name}"), text.clone())));
    }
    out.push(file("templates/NOTES.txt", notes(env)));
    Ok(out)
}

fn chart_file(env: &Environment) -> Result<String, RenderError> {
    let chart = ChartFile {
        api_version: "v2",
        name: env.name.clone(),
        description: format!("The {} environment, generated by Isoloom from isoloom.yml", env.name),
        kind: "application",
        version: "0.1.0",
        app_version: "0.1.0",
    };
    let usage = "# `isoloom chart --version <v>` packages it with that version.\n";
    Ok(format!("{}{usage}{}", generated(), document(&chart)?))
}

/// Each machine's image, as its manifests pull it (through the mirrors; a built one is local),
/// and the inputs, empty.
fn values(env: &Environment, inputs: bool) -> Result<String, RenderError> {
    let values = Values {
        images: Machine::all(env).iter().map(|m| (m.name.to_string(), m.reference.to_string())).collect(),
        inputs: inputs.then(|| env.spec().inputs.iter().map(|i| (i.clone(), String::new())).collect()),
    };
    let usage = "# images: each machine's image (images built from the project must be pushed where the\n# cluster pulls from, and named here). inputs: the launch-time inputs (unset ones are empty).\n";
    Ok(format!("{}{usage}{}", generated(), document(&values)?))
}

/// The manifests but the namespace (the release's), each machine's image its value.
fn environment(r: &Rendered) -> Result<String, RenderError> {
    let objects: Vec<Manifest> = r.objects.iter().filter(|o| o.kind != "Namespace").map(with_image_values).collect();
    Ok(format!("{}{}", generated(), helm_documents(&objects)?))
}

/// `object` with its machine's image (in its containers, init jobs and seeds) the chart's value.
fn with_image_values(object: &Manifest) -> Manifest {
    let mut object = object.clone();
    if let Some(Spec::Deployment(d)) = &mut object.spec {
        let pod = &mut d.template.spec;
        for c in pod.containers.iter_mut().chain(pod.init_containers.iter_mut()) {
            if let Image::Machine { machine, .. } = &c.image {
                c.image = Image::Value { machine: machine.clone() };
            }
        }
    }
    object
}

/// The project's scripts, from the chart's copies (a missing one fails the install, naming it).
fn scripts(scripts: &[String]) -> Result<String, RenderError> {
    let data = scripts.iter().map(|f| {
        let path = format!("{CHART_PROJECT_FILES}/{}", key(f));
        let missing = go_string(&format!("{path} is missing: run isoloom generate"));
        (key(f), Text::Helm(format!("required {missing} (.Files.Get {}) | b64enc", go_string(&path))))
    });
    let map = Manifest::config_map(SCRIPTS, data.collect());
    let about = format!("# The project's scripts (init jobs, checks): copies in {CHART_PROJECT_FILES}/, written by `isoloom generate`.\n");
    Ok(format!("{}{about}{}", generated(), helm_documents(&[map])?))
}

/// The inputs' Secret, from the values (an unset one is empty).
fn secret(env: &Environment) -> Result<String, RenderError> {
    let data = env
        .spec()
        .inputs
        .iter()
        .map(|i| (i.clone(), Text::Helm(format!("get .Values.inputs {} | toString | b64enc", go_string(i)))));
    Ok(format!("{}{}", generated(), helm_documents(&[Manifest::secret(INPUTS, data.collect())])?))
}

/// The checks as `helm test` hooks: their runners' ConfigMap (from the chart's files), then a
/// Pod per Job, named after it (`helm test --logs` reads each test's logs from a pod of the
/// hook's own name).
fn tests(r: &Rendered) -> Result<String, RenderError> {
    let runners = r.checks.runners.iter().map(|(name, _)| {
        (
            name.clone(),
            Text::Helm(format!(".Files.Get {} | b64enc", go_string(&format!("files/checks/{name}")))),
        )
    });
    let mut objects = vec![Manifest::config_map(CHECK_SCRIPTS, runners.collect())];
    let hook = Labels::from([
        ("helm.sh/hook".to_string(), "test".to_string()),
        ("helm.sh/hook-delete-policy".to_string(), "before-hook-creation".to_string()),
    ]);
    for job in &r.checks.jobs {
        if let Some(Spec::Job(j)) = &job.spec {
            let metadata = Metadata {
                name: job.metadata.name.clone(),
                labels: j.template.metadata.labels.clone(),
                annotations: hook.clone(),
            };
            objects.push(Manifest::pod(metadata, j.template.spec.clone()));
        }
    }
    let about = "# The checks: `helm test <release>` runs a Job per position (`exec` checks, run inside a machine,\n# stay with `isoloom test kubernetes`).\n";
    Ok(format!("{}{about}{}", generated(), helm_documents(&objects)?))
}

/// The message as written when it has no placeholders (filling them takes the resolved
/// snapshot, which asks every backend, this one too, whether it would refuse the spec), then
/// how to run the checks.
fn notes(env: &Environment) -> String {
    let mut notes = String::new();
    match env.spec().message.as_deref().map(str::trim_end).filter(|m| !m.trim().is_empty()) {
        Some(m) if !m.contains("{{") => {
            notes.push_str(&literal(m));
            notes.push_str("\n\n");
        }
        Some(_) => notes.push_str("How to use it: isoloom message --target kubernetes (in the project).\n\n"),
        None => {}
    }
    notes.push_str("Checks: helm test {{ .Release.Name }} -n {{ .Release.Namespace }}\n");
    notes
}

/// Helm's template engine reads `{{` as an action: one already in the text is printed as it is.
/// The escape is a Go raw string, with no character a YAML scalar of any style escapes (a
/// double-quoted one would turn `"{{"` into `\"{{\"`, which Helm can't parse).
fn literal(text: &str) -> String {
    text.replace("{{", "{{ `{{` }}")
}

/// Chart templates, one file: every string as it is, but the Helm expressions.
fn helm_documents(objects: &[Manifest]) -> Result<String, RenderError> {
    let docs: Vec<String> = objects.iter().map(helm_document).collect::<Result<_, _>>()?;
    Ok(docs.join("---\n"))
}

fn helm_document(object: &Manifest) -> Result<String, RenderError> {
    let mut value = serde_yaml_ng::to_value(object).map_err(|e| unwritable(&e))?;
    templated(&mut value);
    document(&value)
}

/// `value` as a chart template: its strings escaped ([`literal`]), its Helm expressions (the
/// values tagged [`HELM_TAG`]) in their braces.
fn templated(value: &mut Value) {
    if let Some(expression) = helm_expression(value) {
        *value = Value::String(format!("{{{{ {expression} }}}}"));
        return;
    }
    match value {
        Value::String(s) => *s = literal(s),
        Value::Sequence(items) => items.iter_mut().for_each(templated),
        Value::Mapping(m) => {
            *m = std::mem::take(m)
                .into_iter()
                .map(|(mut k, mut v)| {
                    templated(&mut k);
                    templated(&mut v);
                    (k, v)
                })
                .collect();
        }
        Value::Tagged(t) => templated(&mut t.value),
        Value::Null | Value::Bool(_) | Value::Number(_) => {}
    }
}

/// The expression of a value tagged [`HELM_TAG`].
fn helm_expression(value: &Value) -> Option<String> {
    match value {
        Value::Tagged(t) if t.tag == HELM_TAG => t.value.as_str().map(str::to_string),
        _ => None,
    }
}
